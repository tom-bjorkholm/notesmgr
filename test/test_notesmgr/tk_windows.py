import tkinter

SHOWN_GEOMETRY = '300x400'
"""How large a window that a test really shows is made."""


def show_filled(frame: tkinter.Widget) -> None:
    """Really show a frame on the screen, filling its toplevel window.

    Only tests marked focus_sensitive may do this, so that the normal
    test run never puts a window on the screen.

    Args:
        frame: The frame that is to fill the window that is shown.
    """
    frame.pack(fill=tkinter.BOTH, expand=True)
    window = frame.winfo_toplevel()
    window.geometry(SHOWN_GEOMETRY)
    window.deiconify()
    window.lift()
    window.update()

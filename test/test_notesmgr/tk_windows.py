import tkinter
from tkinter import ttk

SHOWN_GEOMETRY = '300x400'
"""How large a window that a test really shows is made."""


def event_at(height: int, x_root: int = 0,
             y_root: int = 0) -> 'tkinter.Event[ttk.Treeview]':
    """Return a made up Tk event of the pointer at a height in a tree.

    Args:
        height: Where the pointer is in the tree, from its top.
        x_root: Where the pointer is on the screen, from the left.
        y_root: Where the pointer is on the screen, from the top.

    Returns:
        The event, holding the place of the pointer and nothing else.
    """
    event: 'tkinter.Event[ttk.Treeview]' = tkinter.Event()
    event.y, event.x_root, event.y_root = height, x_root, y_root
    return event


def show_filled(frame: tkinter.Widget) -> None:
    """Really show a frame on the screen, filling its toplevel window.

    Only tests marked focus_sensitive may do this, so that the normal
    test run never puts a window on the screen.

    Args:
        frame: The frame that is to fill the window that is shown.
    """
    frame.pack(fill=tkinter.BOTH, expand=True)
    window = frame.winfo_toplevel()
    window.geometry(SHOWN_GEOMETRY)
    window.deiconify()
    window.lift()
    window.update()

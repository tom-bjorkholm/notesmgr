"""Help for tests that drive widgets in windows really shown on screen.

Only a widget of a window that is shown can be relied on to be told
of an event: Tk 9.0.4 silently drops the events meant for a widget of
a withdrawn window that has no native window of its own yet, both
those generated by a test and those that Tk sends itself, while Tk 8.6
and Tk 9.0.2 delivered them.
"""

